import { expect, test } from '@playwright/test'
import { mkdirSync } from 'node:fs'

test.beforeAll(() => mkdirSync('screenshots', { recursive: true }))

const email = 'ci@example.invalid'
const password = process.env.CEO_TEST_PASSWORD

test('mobile CEO login, student lifecycle, and disabled trading', async ({ page }, testInfo) => {
  const studentName = `Orion CI ${testInfo.retry}`
  if (!password) throw new Error('CEO_TEST_PASSWORD required for e2e')
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
  await page.getByLabel('Email address').fill(email)
  await page.getByLabel('Password').fill(password)
  await page.getByRole('button', { name: 'Access console' }).click()
  await expect(page.getByRole('heading', { name: 'Overview', exact: true })).toBeVisible()
  await expect(page.getByText(/No operational broker account or trading permission is active/)).toBeVisible()
  await expect(page.getByText('Historical research is available')).toBeVisible()
  await page.getByRole('button', { name: 'Open Historical replay' }).click()
  await expect(page.getByRole('heading', { name: 'Historical Simulation' })).toBeVisible()
  await page.locator('nav.bottom-nav').getByRole('button', { name: 'Home' }).click()
  await page.screenshot({ path: 'screenshots/01-home-mobile.png', fullPage: true })

  const nav = page.locator('nav.bottom-nav')
  await nav.getByRole('button', { name: 'Students' }).click()
  await expect(page.getByRole('heading', { name: 'Students', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Create student', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Student name').fill(studentName)
  await dialog.getByRole('button', { name: /CEO-directed/ }).click()
  await dialog.getByRole('button', { name: /Gold.*Commodities/ }).click()
  await dialog.getByRole('button', { name: /Trend trading/ }).click()
  await dialog.getByRole('button', { name: 'Create student' }).click()
  await expect(page.getByRole('heading', { name: studentName })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Learning plan v1' })).toBeVisible()
  await page.screenshot({ path: 'screenshots/02-student-mobile.png', fullPage: true })
  await page.getByRole('tab', { name: 'Skills' }).click()
  await expect(page.getByRole('heading', { name: 'Skill Library' })).toBeVisible()
  await expect(page.getByText('Trend trading', { exact: true })).toBeVisible()
  await expect(page.getByText('Unassessed').first()).toBeVisible()
  await page.getByRole('tab', { name: 'Memory' }).click()
  await expect(page.getByRole('heading', { name: 'Good / Bad archive' })).toBeVisible()
  await expect(page.getByText(/No closed research experiences yet/)).toBeVisible()
  await page.screenshot({ path: 'screenshots/02b-skills-memory-mobile.png', fullPage: true })
  await page.getByRole('tab', { name: 'Overview' }).click()

  await page.getByRole('button', { name: 'Change direction' }).click()
  await page.getByRole('dialog').getByRole('button', { name: /Autonomous/ }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Save new plan' }).click()
  await expect(page.getByRole('heading', { name: 'Learning plan v2' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Overview', exact: true })).toBeVisible()
  await nav.getByRole('button', { name: 'Students' }).click()
  await page.locator('button.student-card').filter({ hasText: studentName }).click()
  await expect(page.getByRole('heading', { name: 'Learning plan v2' })).toBeVisible()
  await expect(page.getByText('Learning plan v1')).toBeVisible()

  await nav.getByRole('button', { name: 'Trading' }).click()
  await expect(page.getByRole('heading', { name: 'Trading', exact: true })).toBeVisible()
  await page.getByText('Advanced tools · historical replay, data & paper account').click()
  await page.getByText('Advanced tools · saved data, M1 quotes & engine demonstrations').click()
  await expect(page.getByRole('heading', { name: 'Candle Replay' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Trade and P&L replay' })).toBeVisible()
  await page.getByRole('button', { name: 'Run historical demo' }).click()
  await expect(page.locator('.demo-trade-row').first()).toBeVisible({ timeout: 15000 })
  await page.getByRole('button', { name: 'Pause' }).click()
  await expect(page.getByText(/This demonstration runs on fabricated test data/)).toBeVisible()
  await page.locator('.browser-file-label input[type=file]').setInputFiles({
    name: 'local-m15.csv', mimeType: 'text/csv',
    buffer: Buffer.from('timestamp_open,open,high,low,close\n2025-04-07T09:00:00Z,2000,2003,1998,2001\n2025-04-07T09:15:00Z,2001,2005,2000,2004\n')
  })
  await expect(page.getByText('local-m15.csv')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Play CSV' })).toBeVisible()
  await expect(page.getByText(/No simulated orders, trades, win rate or equity curves/)).toBeVisible()
  await page.screenshot({ path: 'screenshots/03-historical-mobile.png', fullPage: true })
  await page.getByRole('tab', { name: /Paper/ }).click()
  await expect(page.getByRole('heading', { name: 'Paper trading is disabled' })).toBeVisible()
  await expect(page.getByRole('heading', { name: /Simulated account overview/ })).toBeVisible()
  await expect(page.getByText(/Backend credentials not configured/)).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Paper pilot readiness' })).toBeVisible()
  await page.getByRole('tab', { name: /Live/ }).click()
  await expect(page.getByRole('heading', { name: 'Live trading is disabled' })).toBeVisible()
  await page.screenshot({ path: 'screenshots/03-trading-mobile.png', fullPage: true })
})
